//! Text G-code: reads the beginning and the end of the file and nothing in between.
//!
//! Layout seen in real files: PrusaSlicer keeps thumbnails at the start and the sums and the
//! `prusaslicer_config` block at the end; Orca and Creality Print keep a header and thumbnails
//! at the start and the sums plus `CONFIG_BLOCK_START..END` at the end; Bambu Studio keeps
//! sums and the config block in the header; CuraEngine keeps `;KEY:value` lines at the start.

use std::io::{Read, Seek, SeekFrom};

use base64::engine::general_purpose::STANDARD;
use base64::Engine;

use super::{GcodeError, Raw, HEAD_BYTES, MAX_LINE_BYTES, MAX_THUMBNAIL_BYTES, TAIL_BYTES};

/// Base64 characters of a preview image at the size limit (4 characters per 3 bytes, plus padding).
const MAX_THUMBNAIL_CHARS: usize = MAX_THUMBNAIL_BYTES / 3 * 4 + 4;
/// A slicer line ("generated by ...") is looked for in the first lines only.
const MAX_SLICER_LINE: usize = 40;

pub(super) fn read<R: Read + Seek>(source: &mut R, len: u64) -> Result<Raw, GcodeError> {
    let mut raw = Raw::default();
    if len <= HEAD_BYTES + TAIL_BYTES {
        // Short file: one read, one pass, nothing counted twice.
        let bytes = read_range(source, 0, len)?;
        scan(&mut raw, &bytes, Window { first_partial: false, last_partial: false, head: true });
    } else {
        let head = read_range(source, 0, HEAD_BYTES)?;
        scan(&mut raw, &head, Window { first_partial: false, last_partial: true, head: true });
        let tail = read_range(source, len - TAIL_BYTES, TAIL_BYTES)?;
        scan(&mut raw, &tail, Window { first_partial: true, last_partial: false, head: false });
    }
    Ok(raw)
}

fn read_range<R: Read + Seek>(source: &mut R, start: u64, count: u64) -> Result<Vec<u8>, GcodeError> {
    source.seek(SeekFrom::Start(start))?;
    let mut bytes = Vec::new();
    // `take` bounds the read even if the file grows while it is read.
    source.take(count).read_to_end(&mut bytes)?;
    Ok(bytes)
}

/// Which part of a file a buffer is: a window cut out of the middle starts and/or ends inside a line.
#[derive(Clone, Copy)]
struct Window {
    first_partial: bool,
    last_partial: bool,
    head: bool,
}

struct Thumbnail {
    width: u32,
    height: u32,
    declared: usize,
    data: String,
    /// Wrong or too large length, or not Base64: the block is skipped as a whole.
    bad: bool,
}

fn scan(raw: &mut Raw, buf: &[u8], window: Window) {
    let mut thumbnail: Option<Thumbnail> = None;
    let mut line_number = 0usize;
    for_each_line(buf, window, |line| {
        line_number += 1;
        let Some(body) = line.trim_start().strip_prefix(';') else { return };
        let body = body.trim_start();

        if let Some(open) = thumbnail.as_mut() {
            if body.starts_with("thumbnail end") {
                let done = thumbnail.take().expect("open thumbnail");
                finish_thumbnail(raw, done);
            } else if !open.bad {
                let text: String = body.chars().filter(|c| !c.is_whitespace()).collect();
                if open.data.len() + text.len() > open.declared {
                    open.bad = true;
                    open.data.clear();
                } else {
                    open.data.push_str(&text);
                }
            }
            return;
        }
        if let Some(rest) = body.strip_prefix("thumbnail begin ") {
            thumbnail = Some(begin_thumbnail(rest));
            return;
        }

        if body == "CONFIG_BLOCK_START" || body.ends_with("_config = begin") {
            raw.config = true;
            raw.recognized = true;
            return;
        }
        if window.head && line_number <= MAX_SLICER_LINE {
            detect_slicer(raw, body);
        }
        if let Some((key, value)) = split_pair(body) {
            raw.put(key, value);
            // Bambu Studio and Orca: `; model printing time: 13m 18s; total estimated time: 19m 34s`.
            if key == "model printing time" {
                for part in value.split(';').skip(1) {
                    if let Some((key, value)) = split_pair(part.trim_start()) {
                        raw.put(key, value);
                    }
                }
            }
        }
    });
}

fn detect_slicer(raw: &mut Raw, body: &str) {
    if let Some(rest) = body.strip_prefix("generated by ") {
        // `PrusaSlicer 2.8.1+linux-x64-GTK3 on 2026-11-04 at 20:30:25 UTC`
        let mut words = rest.split_whitespace();
        if let Some(name) = words.next() {
            let version = words.next().filter(|w| *w != "on");
            raw.set_slicer(name, version);
        }
    } else if let Some(rest) = body.strip_prefix("Generated with ") {
        // CuraEngine: `;Generated with Cura_SteamEngine 5.13.0`
        let mut words = rest.split_whitespace();
        if let Some(name) = words.next() {
            raw.set_slicer(name, words.next());
        }
    } else if let Some(version) = body.strip_prefix("BambuStudio ") {
        let version = version.trim();
        if version.starts_with(|c: char| c.is_ascii_digit()) && !version.contains(' ') {
            raw.set_slicer("BambuStudio", Some(version));
        }
    }
}

/// `key = value` (settings and sums) or `key: value` / `key:value` (headers).
fn split_pair(body: &str) -> Option<(&str, &str)> {
    if let Some(i) = body.find(" = ") {
        return Some((&body[..i], &body[i + 3..]));
    }
    if let Some(key) = body.trim_end().strip_suffix(" =") {
        return Some((key, ""));
    }
    let i = body.find(':')?;
    Some((&body[..i], &body[i + 1..]))
}

fn begin_thumbnail(rest: &str) -> Thumbnail {
    // `220x124 4612`: size and the number of Base64 characters that follow.
    let mut parts = rest.split_whitespace();
    let size = parts.next().and_then(|s| s.split_once('x'));
    let width = size.and_then(|(w, _)| w.parse::<u32>().ok());
    let height = size.and_then(|(_, h)| h.parse::<u32>().ok());
    let declared = parts.next().and_then(|n| n.parse::<usize>().ok());
    match (width, height, declared) {
        (Some(width), Some(height), Some(declared)) if declared > 0 && declared <= MAX_THUMBNAIL_CHARS => {
            Thumbnail { width, height, declared, data: String::new(), bad: false }
        }
        _ => Thumbnail { width: 0, height: 0, declared: 0, data: String::new(), bad: true },
    }
}

fn finish_thumbnail(raw: &mut Raw, thumbnail: Thumbnail) {
    // The announced length is the number of characters; any difference means the block is not what it says.
    if thumbnail.bad || thumbnail.data.len() != thumbnail.declared {
        return;
    }
    if let Ok(png) = STANDARD.decode(thumbnail.data.as_bytes()) {
        raw.add_thumbnail(thumbnail.width, thumbnail.height, png);
    }
}

/// Calls `f` for each complete line. Lines over [`MAX_LINE_BYTES`] are skipped without being copied.
fn for_each_line(buf: &[u8], window: Window, mut f: impl FnMut(&str)) {
    let mut start = 0;
    if window.first_partial {
        match buf.iter().position(|&b| b == b'\n') {
            Some(i) => start = i + 1,
            None => return,
        }
    }
    while start < buf.len() {
        let (end, next, terminated) = match buf[start..].iter().position(|&b| b == b'\n') {
            Some(i) => (start + i, start + i + 1, true),
            None => (buf.len(), buf.len(), false),
        };
        if !terminated && window.last_partial {
            break;
        }
        let mut line = &buf[start..end];
        if line.last() == Some(&b'\r') {
            line = &line[..line.len() - 1];
        }
        if !terminated && std::str::from_utf8(line).is_err() {
            // A last line cut inside a multi-byte character would give a damaged value.
            break;
        }
        if line.len() <= MAX_LINE_BYTES {
            f(&String::from_utf8_lossy(line));
        }
        start = next;
    }
}
